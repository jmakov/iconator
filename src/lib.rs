//! Look up file and folder icon IDs by path.
//!
//! Each ID identifies an SVG in the icon set: for example, `525` corresponds to
//! `icons/525.svg`. Lookups are case-sensitive and use embedded tables, so the
//! path does not need to exist on disk.

use fst::Map;
use lazy_static::lazy_static;
use std::{os::unix::ffi::OsStrExt, path::Path};

// `build.rs` generates the bytes for each lookup table. On first use, each
// map borrows its embedded bytes and is then shared by all lookup threads.
lazy_static! {
    /// Maps exact filenames (including any extension) to icon IDs.
    static ref FILENAME_ICONS: Map<&'static [u8]> = {
        const FILENAME_ICONS_BYTES: &[u8] =
            include_bytes!(concat!(env!("OUT_DIR"), "/filename_icons.bin"));

        // Safety: the bytes are correctly generated by fst in the build script, so we can use `unwrap_unchecked`
        unsafe { Map::new(FILENAME_ICONS_BYTES).unwrap_unchecked() }
    };
    /// Maps final extensions without the leading dot to icon IDs when the filename misses.
    static ref EXT_ICONS: Map<&'static [u8]> = {
        const EXT_ICONS_BYTES: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/ext_icons.bin"));

        // Safety: the bytes are correctly generated by fst in the build script, so we can use `unwrap_unchecked`
        unsafe {
            Map::new(EXT_ICONS_BYTES).unwrap_unchecked()
        }
    };
    /// Maps folder names, without their parent directories, to icon IDs.
    static ref FOLDER_ICONS: Map<&'static [u8]> = {
        const FOLDER_ICONS_BYTES: &[u8] =
            include_bytes!(concat!(env!("OUT_DIR"), "/folder_icons.bin"));

        // Safety: the bytes are correctly generated by fst in the build script, so we can use `unwrap_unchecked`
        unsafe { Map::new(FOLDER_ICONS_BYTES).unwrap_unchecked() }
    };
}

/// Choose a file icon by exact filename, then by final extension.
///
/// # Arguments
///
/// * `path` - File path as it appears in the client's project tree. Matching is
///   case-sensitive and uses only the final component.
///
/// # Returns
///
/// The matched SVG's numeric ID, or `None` for an unlisted file or a path
/// without a basename. A match describes the name even if the file does not exist.
///
/// # Examples
///
/// ```
/// use iconator::get_icon_for_file;
///
/// assert_eq!(get_icon_for_file("project/.babelrc.js"), Some(40));
/// assert_eq!(get_icon_for_file("project/index.js"), Some(296));
/// assert_eq!(get_icon_for_file("project/unlisted-file"), None);
/// assert_eq!(get_icon_for_file("/"), None);
/// ```
pub fn get_icon_for_file(path: impl AsRef<Path>) -> Option<u64> {
    let path = path.as_ref();
    // Safety: handle path without file name e.g. `/`
    let basename = path.file_name()?;

    FILENAME_ICONS.get(basename.as_bytes()).or_else(|| {
        // Safety: handle unlisted path without an extension
        let ext = path.extension()?;

        EXT_ICONS.get(ext.as_bytes())
    })
}

/// Choose a folder icon by its own name.
///
/// # Arguments
///
/// * `path` - Path to the folder itself. Passing a child's path looks up the
///   child's name instead.
///
/// # Returns
///
/// The matched SVG's numeric ID, or `None` if the folder name is absent from
/// the table or the path has no basename.
///
/// # Examples
///
/// ```
/// use iconator::get_icon_for_folder;
///
/// assert_eq!(get_icon_for_folder("project/src"), Some(1054));
/// assert_eq!(get_icon_for_folder("/"), None);
/// ```
pub fn get_icon_for_folder(path: impl AsRef<Path>) -> Option<u64> {
    let path = path.as_ref();
    // Safety: handle path without file name e.g. `/`
    let basename = path.file_name()?;

    FOLDER_ICONS.get(basename.as_bytes())
}

/// Regression cases for common names, lookup misses, and paths without a basename.
#[cfg(test)]
mod test {
    use super::*;

    /// Pin the icon IDs used for common source and configuration file extensions.
    #[test]
    fn common_languages() {
        assert_eq!(get_icon_for_file("./test.js"), Some(296));
        assert_eq!(get_icon_for_file("./test.ts"), Some(633));
        assert_eq!(get_icon_for_file("./test.jsx"), Some(508));
        assert_eq!(get_icon_for_file("./test.tsx"), Some(529));
        assert_eq!(get_icon_for_file("./test.json"), Some(284));
        assert_eq!(get_icon_for_file("./test.yaml"), Some(708));
        assert_eq!(get_icon_for_file("./test.yml"), Some(708));
        assert_eq!(get_icon_for_file("./test.md"), Some(361));
        assert_eq!(get_icon_for_file("./test.css"), Some(116));
        assert_eq!(get_icon_for_file("./test.html"), Some(255));
        assert_eq!(get_icon_for_file("./test.rs"), Some(525));
    }

    /// Cover both hidden and ordinary directory names found in project trees.
    #[test]
    fn common_folders() {
        assert_eq!(get_icon_for_folder("./.github"), Some(862));
        assert_eq!(get_icon_for_folder("./src"), Some(1054));
        assert_eq!(get_icon_for_folder("./tests"), Some(1084));
    }

    /// An unknown extensionless file has neither an exact match nor a fallback.
    #[test]
    fn unlisted_path_returns_none() {
        assert_eq!(get_icon_for_file("path_not_listed_and_without_extension"), None);
    }

    /// A filesystem root has no filename to feed into either file lookup.
    #[test]
    fn file_without_basename_returns_none() {
        assert_eq!(get_icon_for_file("/"), None);
    }

    /// The root directory has no folder name to match against the table.
    #[test]
    fn folder_without_basename_returns_none() {
        assert_eq!(get_icon_for_folder("/"), None);
    }
}
